#!/usr/bin/env bash
#
# scripts/new-template.sh — Scaffoldea una nueva plantilla en el catálogo.
#
# Uso:
#   ./scripts/new-template.sh <name> "<description>" <source-repo-url>
#
# Ejemplo:
#   ./scripts/new-template.sh my-template \
#     "POS multi-vendor para food delivery en LATAM" \
#     "https://github.com/vendor/food-pos-template.git"
#
# El script:
#   1. Crea la estructura de directorios
#   2. Inicializa el submodule
#   3. Genera SKILL.md + INTEGRATION.md stubs
#   4. Genera repomix.txt placeholder
#   5. Actualiza .gitmodules
#

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO_ROOT"

# 1. Validar args
if [ "$#" -ne 3 ]; then
  echo "Uso: $0 <name> \"<description>\" <source-repo-url>"
  echo "  name:           kebab-case-id (e.g., 'food-pos', 'marketplace-mv')"
  echo "  description:    2-4 line summary of the template's purpose"
  echo "  source-repo-url: HTTPS URL to the upstream MIT/Apache repo"
  exit 1
fi

NAME="$1"
DESCRIPTION="$2"
SOURCE_URL="$3"
TEMPLATE_DIR="templates/$NAME"
SOURCE_DIR="$TEMPLATE_DIR/source"

# 2. Validar name (kebab-case, lowercase)
if ! [[ "$NAME" =~ ^[a-z0-9]+(-[a-z0-9]+)*$ ]]; then
  echo "ERROR: name debe ser kebab-case (lowercase + hyphens). Ej: 'food-pos', 'marketplace-mv'"
  exit 1
fi

# 3. Validar que no exista ya
if [ -d "$TEMPLATE_DIR" ]; then
  echo "ERROR: $TEMPLATE_DIR ya existe. Elige otro name o elimina el existente."
  exit 1
fi

# 4. Validar URL
if ! [[ "$SOURCE_URL" =~ ^https://github\.com/.+/.+\.git$ ]]; then
  echo "WARN: URL no parece ser un repo GitHub estándar. Continúo, pero verifica."
fi

echo "Scaffolding new template: $NAME"
echo "  Description: $DESCRIPTION"
echo "  Source URL:  $SOURCE_URL"
echo ""

# 5. Crear estructura
mkdir -p "$SOURCE_DIR"
echo "✓ Created $TEMPLATE_DIR/"

# 6. Generar SKILL.md stub
cat > "$TEMPLATE_DIR/SKILL.md" <<EOF
---
name: $NAME
description: |
  $DESCRIPTION

  Use when: TODO — describe when to activate this skill.
  Don't use for: TODO — describe when NOT to activate.

  Stack: TODO — fill in the framework/library
  License: TODO — MIT, Apache-2.0, or other
  Source: $SOURCE_URL
  Integration target: opita-market-templates v0.1.0+
---

# $NAME — TODO short description

## Status: ⚠️ Just scaffolded — needs real customization

This SKILL.md is a placeholder generated by \`scripts/new-template.sh\`. Fill in:

1. **description**: 2-4 line summary (above)
2. **Stack**: framework + key libraries
3. **License**: check the upstream LICENSE file
4. **Endpoints consumed**: see [\`../docs/api-cookbook.md\`](../docs/api-cookbook.md)
5. **Customization tips**: what to change per tenant
6. **Pitfalls**: what NOT to do

## When to activate

TODO

## When NOT to activate

TODO

## Reference

- Upstream: $SOURCE_URL
- Source code (submodule): \`source/\`
- Compressed context: \`repomix.txt\` (regenerate with \`./scripts/repack.sh\`)
- Backend integration cookbook: [\`../docs/api-cookbook.md\`](../docs/api-cookbook.md)
EOF
echo "✓ Created $TEMPLATE_DIR/SKILL.md"

# 7. Generar INTEGRATION.md stub
cat > "$TEMPLATE_DIR/INTEGRATION.md" <<EOF
# $NAME — INTEGRATION.md

> **⚠️ PLACEHOLDER.** Generated by \`scripts/new-template.sh\`. Fill in the
> concrete integration steps for this template.

When customized, this document should contain:

1. Prerequisites + env vars
2. Auth via OCAIS cookie (pattern: see \`../admin-tailadmin/INTEGRATION.md §2\`)
3. API client wrapper for \`opita-market-templates\`
4. Page-by-page mapping (which backend endpoint → which UI page)
5. Customization (Tailwind tokens + brand)
6. Deploy steps (Vercel / Cloudflare Pages / Docker)
7. End-to-end verification checklist

The pattern mirrors \`../admin-tailadmin/INTEGRATION.md\` and
\`../ecommerce-storefront/INTEGRATION.md\`.
EOF
echo "✓ Created $TEMPLATE_DIR/INTEGRATION.md"

# 8. Generar repomix.txt placeholder
cat > "$TEMPLATE_DIR/repomix.txt" <<EOF
# Placeholder para repomix.txt

Este archivo será regenerado por:

\`\`\`bash
./scripts/repack.sh templates/$NAME
\`\`\`

Requiere que primero inicialices el submodule:

\`\`\`bash
git submodule update --init --recursive
\`\`\`
EOF
echo "✓ Created $TEMPLATE_DIR/repomix.txt"

# 9. Generar source/.gitkeep
cat > "$SOURCE_DIR/.gitkeep" <<EOF
# Submodule: $NAME
#
# Vendored from: $SOURCE_URL
# License: TODO — fill in after checking upstream
#
# To populate this directory, run from the repo root:
#   git submodule update --init --recursive
#
# See ../SKILL.md and ../INTEGRATION.md for customization instructions.

This directory is a git submodule. Do not commit files here directly.
EOF
echo "✓ Created $SOURCE_DIR/.gitkeep"

# 10. Agregar al .gitmodules (auto)
if ! grep -q "$SOURCE_URL" .gitmodules 2>/dev/null; then
  cat >> .gitmodules <<EOF

[submodule "$SOURCE_DIR"]
	path = $SOURCE_DIR
	url = $SOURCE_URL
	branch = main
EOF
  echo "✓ Appended to .gitmodules"
else
  echo "✓ $SOURCE_URL already in .gitmodules"
fi

# 11. Inicializar el submodule
echo ""
echo "Inicializando submodule..."
if git submodule add "$SOURCE_URL" "$SOURCE_DIR" 2>&1; then
  echo "✓ Submodule initialized"
else
  echo "WARN: submodule add falló. Puedes correrlo manualmente:"
  echo "  git submodule add $SOURCE_URL $SOURCE_DIR"
fi

# 12. Validar
echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "✓ Template scaffolded: $NAME"
echo ""
echo "Próximos pasos:"
echo "  1. Personalizar $TEMPLATE_DIR/SKILL.md (description + stack + license)"
echo "  2. Personalizar $TEMPLATE_DIR/INTEGRATION.md (endpoints + pasos)"
echo "  3. Verificar el submodule:"
echo "       ls $SOURCE_DIR"
echo "  4. Generar repomix.txt:"
echo "       ./scripts/repack.sh $TEMPLATE_DIR"
echo "  5. Validar:"
echo "       ./scripts/validate-skills.sh"
echo "  6. Commit:"
echo "       git add $TEMPLATE_DIR/ .gitmodules && git submodule status"
echo "       git commit -m 'feat(templates): add $NAME'"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"